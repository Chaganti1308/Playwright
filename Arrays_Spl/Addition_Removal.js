// Add more values to array

let arr = [3,4,5,1,6];

// Array Manipulation -- push(),unshift(),pop(),shift()

// push() -- adds at the last of array
arr.push(10);
console.log("After push ",arr);

// unshift() -- adds at the start

arr.unshift(-1);
console.log("After unshift ",arr);

// shift() -- remove elements at start
arr.shift();
console.log("After shift ",arr);

// popo() - removes elements from last
arr.pop();
console.log("After pop ",arr);



