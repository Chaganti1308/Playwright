// = , == , ===

 

let a = 5; // assignment

 

// check the value only

console.log(5 == 5);

console.log(5 == '5');

 

// checks the value along with datatype.

console.log(5 === '5');

 

console.log(null == undefined); // true

console.log(null === undefined); // False

 

console.log(5 == 5.0); // true

console.log(5 === 5.0); // true

console.log(5 === 5.01); // false