// Arithmetic Operators -- used to perform mathematical operations
let a = 7;
let b = 3;

let sum = a + b; // Addition
let sub = a - b; // Subtraction
let mul = a * b; // Multiplication
let div = a / b; // Division
let mod = a % b; // Modulus
let exp = a ** b; // Exponentiation

console.log(sum); // Output: 10
console.log(sub); // Output: 4
console.log(mul); // Output: 21
console.log(div); // Output: 2.3333333333333335
console.log(mod); // Output: 1
console.log(exp); // Output: 343