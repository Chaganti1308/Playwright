// comparison -- > it is used to compare two values and return a boolean value (true or false)

// > , < , >= , <= , == , === , != , !==

let a = 10;
let b = 20;

console.log(a > b); // Output: false
console.log(a < b); // Output: true
console.log(a >= b); // Output: false
console.log(a <= b); // Output: true
console.log(a == b); // Output: false
console.log(a === b); // Output: false
console.log(a != b); // Output: true
console.log(a !== b); // Output: true
