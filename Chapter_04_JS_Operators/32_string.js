// string concatenation
let str1 = "Hello..";
let str2 = "World";
let result = str1 + " " + str2;

console.log(result); // Output: "Hello.. World"

let s1 = "Hello. ";
let s2 = "World";
let s3 = s1 + s2;
console.log(s3); // Output: "Hello. World"

let s = "Hello.. ";
s += "World!";
console.log(s); // Output: "Hello.. World!"