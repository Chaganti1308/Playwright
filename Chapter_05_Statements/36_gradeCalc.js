let score = 100;

if(score >= 90){
    console.log("Grade - A -> Excellent");
    
} else if(score >= 75 && score < 90){
    console.log("Grade - B -> Good");
    
}else if(score >= 55 && score < 75){
    console.log("Grade - C -> Average");
    
}else if(score >= 45 && score < 55){
    console.log("Grade - D -> Below Average");
    
} else {
    console.log("Fail");
    
}