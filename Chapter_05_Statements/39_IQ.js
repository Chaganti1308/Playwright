// truthy statements
if("hello") console.log("Hello World");
if(" ") console.log("Hello World-1");
if([]) console.log("Hello World-2");
if({}) console.log("Hello World-3");

// falsy statements
if("") console.log("Hello World1");
if(null) console.log("Hello World2");
if(undefined) console.log("Hello World3");
if(NaN) console.log("Hello World4");
