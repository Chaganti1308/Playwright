// pre increment -- increments first andd assigns
let a = 10;
let b = ++a; // a = a+1



console.log("Pre Increment -- a:10, b:NA"); 
console.log("a : ",a); // 11
console.log("b : ",b); // 11

// post increment -- first assigns and then increments

console.log("Post Increment -- c:13, d:NA"); 
let c = 13;
let d = c++;

console.log("c :",c); // 14
console.log("d :",d); // 13

// pre decrement 
let i = 5;
let j = --i;

console.log("Pre decrement -- i:5, j:NA"); 
console.log("i :",i); // 4
console.log("j :",j); // 4

// post decrement

let k = 16;
let l = k--;

console.log("Post decrement -- k:16, l:NA"); 
console.log("k :",k); // 15
console.log("l :",l); // 16




